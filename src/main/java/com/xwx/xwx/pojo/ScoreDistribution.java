package com.xwx.xwx.pojo;

public class ScoreDistribution {
    private int A;
    private int B;
    private int C;
    private int D;
    private int E;
    private int F;

    // Getters and Setters
    public int getA() {
        return A;
    }

    public void setA(int A) {
        this.A = A;
    }

    public int getB() {
        return B;
    }

    public void setB(int B) {
        this.B = B;
    }

    public int getC() {
        return C;
    }

    public void setC(int C) {
        this.C = C;
    }

    public int getD() {
        return D;
    }

    public void setD(int D) {
        this.D = D;
    }

    public int getE() {
        return E;
    }

    public void setE(int E) {
        this.E = E;
    }

    public int getF() {
        return F;
    }

    public void setF(int F) {
        this.F = F;
    }

    @Override
    public String toString() {
        return "ScoreDistribution{" +
                "A=" + A +
                ", B=" + B +
                ", C=" + C +
                ", D=" + D +
                ", E=" + E +
                ", F=" + F +
                '}';
    }
}

